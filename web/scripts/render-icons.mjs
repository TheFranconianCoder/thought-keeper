/**
 * Renders Thought Keeper's app icons from the studio pictogram.
 *
 * The pictogram in `web/icons/pictogram.svg` (a copy of
 * `studio-page/design/pictograms/thought-keeper.svg`) is the artwork — it is never redrawn,
 * only reframed. The pictogram's full-bleed square background is replaced by a **squircle**:
 * a superellipse `|x/a|^n + |y/a|^n = 1`, sampled densely so the corners curve continuously
 * instead of meeting a rounded box's arc. That is what an app icon should look like when the
 * platform does not mask it itself (Windows taskbar, Linux dock, the tray, a browser tab).
 *
 *   node scripts/render-icons.mjs          # write the icons
 *   node scripts/render-icons.mjs --check  # only report what would change
 *
 * sharp is not a dependency of this package (the web build does not need it). The script finds
 * it in `web/node_modules`, `../studio-page/node_modules` or `../../studio-page/node_modules`;
 * install it with `npm i -D sharp` if none of them has it.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(WEB, '..');
const PUBLIC = path.join(WEB, 'public');
const PICTOGRAM = path.join(WEB, 'icons', 'pictogram.svg');
const TRAY_ICON = path.join(REPO, 'internal', 'app', 'icon.png');

/** The icon canvas. Every asset is derived from it, so the geometry below is size-independent. */
const SIZE = 512;
/** Superellipse exponent. 5 is the squircle as the operating systems draw it; 2 is a circle,
 *  → ∞ a square. Below ~4 the corners look like a rounded box, above ~8 like a cut corner. */
const EXPONENT = 5;
/** Samples per quadrant: the path is a polygon, and this is how fine its chords are. 64 is
 *  below a tenth of a pixel at 512 and still smooth at any size. */
const PER_QUADRANT = 64;
/** The pictogram's background — the same graphite as the manifest's theme/background color. */
const BACKGROUND = '#0b0f14';
/* A maskable icon is masked into a circle of 80% diameter, so the mark must stay inside it.
 * No scaling is needed: the pictogram's furthest point is a node centre 168 px from the canvas
 * centre (0.66·R), the safe circle is 0.80·R — the artwork already lives well inside it. */
/** Tray sizes are 22–32 px, where a 14/512 stroke lands below one pixel; the studio's own
 *  template stroke weight (16) with proportionally larger nodes keeps the mark readable. */
const TRAY_STROKE = 16;
const TRAY_NODE_RADIUS = 21;
const TRAY_CENTER_RADIUS = 27;

const sharp = loadSharp();

function loadSharp() {
	const candidates = [
		'sharp',
		path.join(WEB, 'node_modules', 'sharp'),
		path.join(REPO, '..', 'studio-page', 'node_modules', 'sharp'),
		path.join(REPO, 'studio-page', 'node_modules', 'sharp'),
	];
	for (const candidate of candidates) {
		try {
			return require(candidate);
		} catch {
			/* try the next one */
		}
	}
	throw new Error(
		'sharp not found. Run `npm i -D sharp` in web/, or render from a checkout with ' +
			'../studio-page installed (studio-page depends on sharp).'
	);
}

/** squirclePath returns the closed superellipse outline as one path. */
function squirclePath(size, exponent = EXPONENT, perQuadrant = PER_QUADRANT) {
	const r = size / 2;
	const total = perQuadrant * 4;
	const points = [];
	for (let i = 0; i < total; i++) {
		const t = (i / total) * 2 * Math.PI;
		const cos = Math.cos(t);
		const sin = Math.sin(t);
		// |cos|^(2/n) and |sin|^(2/n) satisfy |x/r|^n + |y/r|^n = 1 exactly.
		const x = Math.sign(cos) * Math.abs(cos) ** (2 / exponent) * r;
		const y = Math.sign(sin) * Math.abs(sin) ** (2 / exponent) * r;
		points.push(`${(r + x).toFixed(2)} ${(r + y).toFixed(2)}`);
	}
	return `M${points.join('L')}Z`;
}

/** artwork extracts everything but the pictogram's full-bleed background rectangle. */
function artwork(pictogram) {
	const rect = pictogram.match(/<rect[^>]*\/>/);
	if (!rect) {
		throw new Error(`${PICTOGRAM}: no background <rect> to replace — the pictogram changed shape`);
	}
	const start = pictogram.indexOf(rect[0]) + rect[0].length;
	const end = pictogram.lastIndexOf('</svg>');
	return pictogram.slice(start, end < 0 ? undefined : end);
}

/** appIconSvg is the squircle app icon: artwork on the graphite squircle, transparent outside. */
function appIconSvg(markup) {
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}" role="img" aria-label="Thought Keeper">
  <title>Thought Keeper</title>
  <!-- Generated by web/scripts/render-icons.mjs: the studio pictogram on a superellipse
       (squircle) background. Do not hand-edit; edit web/icons/pictogram.svg and re-render. -->
  <path fill="${BACKGROUND}" d="${squirclePath(SIZE)}" />
  <g>
${markup.trimEnd()}
  </g>
</svg>
`;
}

/** fullBleedSvg is the square, opaque variant: for icons the platform masks itself (the
 *  maskable one and iOS's apple-touch-icon). */
function fullBleedSvg(markup) {
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">
  <rect width="${SIZE}" height="${SIZE}" fill="${BACKGROUND}" />
${markup.trimEnd()}
</svg>
`;
}

/** maskableSvg fills the whole canvas: the platform masks it, and cropping is expected. */
function maskableSvg(markup) {
	return fullBleedSvg(markup);
}

/** tinySvg is the tray render: same artwork, a stroke that survives a 22–32 px raster. */
function tinySvg(markup) {
	const thick = markup
		.replaceAll('stroke-width="14"', `stroke-width="${TRAY_STROKE}"`)
		.replaceAll('r="18"', `r="${TRAY_NODE_RADIUS}"`)
		.replaceAll('r="24"', `r="${TRAY_CENTER_RADIUS}"`);
	return appIconSvg(thick);
}

async function png(svg, size, { alpha }) {
	const image = sharp(Buffer.from(svg), { density: 384 }).resize(size, size, { fit: 'fill' });
	return (alpha ? image : image.flatten({ background: BACKGROUND })).png({ compressionLevel: 9 }).toBuffer();
}

const outputs = [];
async function write(target, data) {
	outputs.push({ target, data });
}

const check = process.argv.includes('--check');

const main = async () => {
	const pictogram = await fs.readFile(PICTOGRAM, 'utf8');
	const mark = artwork(pictogram);
	const squircle = appIconSvg(mark);

	await write(path.join(PUBLIC, 'icon.svg'), Buffer.from(squircle));
	await write(path.join(PUBLIC, 'icon-192.png'), await png(squircle, 192, { alpha: true }));
	await write(path.join(PUBLIC, 'icon-512.png'), await png(squircle, 512, { alpha: true }));
	await write(path.join(PUBLIC, 'icon-maskable-512.png'), await png(maskableSvg(mark), 512, { alpha: false }));
	// iOS never sees the SVG and does not read `purpose: maskable`: it wants a plain 180 px
	// square and applies its own squircle.
	await write(path.join(PUBLIC, 'apple-touch-icon.png'), await png(fullBleedSvg(mark), 180, { alpha: false }));
	await write(TRAY_ICON, await png(tinySvg(mark), 32, { alpha: true }));

	let changed = 0;
	for (const { target, data } of outputs) {
		const before = await fs.readFile(target).catch(() => undefined);
		const same = before !== undefined && before.equals(data);
		const rel = path.relative(REPO, target);
		if (same) {
			console.log(`= ${rel}`);
			continue;
		}
		changed++;
		if (check) {
			console.log(`✦ ${rel} would change`);
			continue;
		}
		await fs.mkdir(path.dirname(target), { recursive: true });
		await fs.writeFile(target, data);
		console.log(`✦ ${rel} written (${data.length} bytes)`);
	}
	if (check && changed > 0) process.exitCode = 1;
};

await main();
